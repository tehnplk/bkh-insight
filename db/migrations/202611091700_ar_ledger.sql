-- หนึ่งแถวต่อการกดดึงยอด (รายวัน หรือ backfill หนึ่งเดือน)
CREATE TABLE ar_sync_log (
  id bigserial PRIMARY KEY,
  mode text NOT NULL CHECK (mode IN ('daily', 'backfill')),
  range_start date NOT NULL,
  range_end date NOT NULL,
  counts jsonb NOT NULL DEFAULT '{}',   -- { "opd_set": n, "opd_adjust": n, "opd_cancel": n, "ipd_set": n, ... }
  requested_by text,
  started_at timestamptz NOT NULL DEFAULT now(),
  finished_at timestamptz,
  error text
);
CREATE INDEX ar_sync_log_started_idx ON ar_sync_log (started_at DESC);

-- สมุดลูกหนี้: amount บวก = ตั้ง/เพิ่ม ลบ = ลด ยอดคงเหลือของ ref = SUM(amount) ของ (source, ref)
--   source: rcpt_debt (OPD ref = debt_id), ipt (IPD ref = an); เฟสถัดไป: stm (ตัดหนี้ด้วย STM ผ่าน REP TRAN_ID), manual (งานบัญชีบันทึกเอง)
--   kind: set ตั้งหนี้, adjust ปรับปรุงส่วนต่าง, cancel ยกเลิกหนี้ (rcpt_debt_cancel), reverse กลับรายการ (IPD ยกเลิกปิดสิทธิ์), settle ตัดหนี้
--   ref_date: OPD = debt_date, IPD = dchdate ; entry_date = วันที่ลงบัญชี (ใช้แบ่งงวด)
--   pttype ถึง account_code คัดลอกจากแถว set ทุกแถวของ ref เดียวกัน ยอดจึงอยู่บัญชีเดียวกันเสมอ
CREATE TABLE ar_ledger (
  id bigserial PRIMARY KEY,
  source text NOT NULL CHECK (source IN ('rcpt_debt', 'ipt', 'stm', 'manual')),
  kind text NOT NULL CHECK (kind IN ('set', 'adjust', 'cancel', 'reverse', 'settle')),
  ref text NOT NULL,
  vn varchar(13),
  an varchar(12),
  patient_type text NOT NULL CHECK (patient_type IN ('OP', 'IP')),
  ref_date date,
  entry_date date NOT NULL,
  pttype text,
  hipdata_code text,
  hospmain text,
  hospmain_chwpart text,
  account_code text REFERENCES ar_account,   -- NULL = ไม่ระบุบัญชี (ยังไม่มี mapping)
  amount numeric(14,2) NOT NULL CHECK (amount <> 0),
  note text,                                 -- เหตุผล
  sync_id bigint REFERENCES ar_sync_log,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- ตั้งหนี้และยกเลิกได้ครั้งเดียวต่อ ref (กันกดซ้ำ) ส่วน adjust/reverse กันซ้ำด้วยการเทียบยอดคงเหลือใน transaction ที่ถือ advisory lock
CREATE UNIQUE INDEX ar_ledger_once_uq ON ar_ledger (source, ref, kind) WHERE kind IN ('set', 'cancel');
CREATE INDEX ar_ledger_ref_idx ON ar_ledger (source, ref);
CREATE INDEX ar_ledger_entry_date_idx ON ar_ledger (entry_date);
CREATE INDEX ar_ledger_account_idx ON ar_ledger (account_code, entry_date);
CREATE INDEX ar_ledger_ref_date_idx ON ar_ledger (source, ref_date) WHERE kind = 'set';
