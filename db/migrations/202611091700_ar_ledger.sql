-- สิทธิ -> บัญชี: ตามกองทุน (pttype.hipdata_code) หรือ override ราย pttype (มาก่อนกองทุน) แยก OP/IP
-- UCS OP ไม่อยู่ในตารางนี้: แยกตามหน่วยบริการประจำในโค้ด (src/app/api/fund/ar-sync/ledger.ts) ยกเว้นมี override ราย pttype
CREATE TABLE ar_account_map (
  id bigserial PRIMARY KEY,
  hipdata_code text,
  pttype text,
  patient_type text NOT NULL CHECK (patient_type IN ('OP', 'IP')),
  account_code text NOT NULL REFERENCES ar_account,
  updated_by text,
  updated_at timestamptz NOT NULL DEFAULT now(),
  CHECK (num_nonnulls(hipdata_code, pttype) = 1)
);
CREATE UNIQUE INDEX ar_account_map_fund_uq ON ar_account_map (hipdata_code, patient_type) WHERE hipdata_code IS NOT NULL;
CREATE UNIQUE INDEX ar_account_map_pttype_uq ON ar_account_map (pttype, patient_type) WHERE pttype IS NOT NULL;

