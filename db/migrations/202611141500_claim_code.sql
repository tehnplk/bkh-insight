-- ที่มา: ประกาศ สปสช. เรื่อง การจ่ายค่าใช้จ่ายเพื่อบริการสาธารณสุข กรณีการให้บริการอุปกรณ์และอวัยวะเทียมในการบำบัดรักษาโรค พ.ศ. 2568
