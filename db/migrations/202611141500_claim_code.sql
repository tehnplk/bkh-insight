  kind text NOT NULL CHECK (kind IN ('INST', 'PP')),
  code text NOT NULL CHECK (code ~ '^[0-9A-Z_]{2,15}$'),
  name text,
  rate numeric(12,2),
  attachment text,
  PRIMARY KEY (kind, code)
);

