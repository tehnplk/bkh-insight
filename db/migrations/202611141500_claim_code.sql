-- อัตราตรงกับ nhso_adp_code.UCS ของ HOSxP 349 รหัส ; rate NULL = อ่านจากไฟล์ไม่ได้ (หน้าแสดง UCS ของ HOSxP แทน)
-- kind PP: ยังไม่มีไฟล์ประกาศที่มีรหัส หน้าใช้ nhso_adp_code ประเภท 4 ของ HOSxP เป็นรายการอ้างอิง
