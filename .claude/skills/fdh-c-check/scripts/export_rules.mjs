// สร้าง sql/, sql/manifest.json, references/levels.json, references/c_codes.json ของ skill fdh-c-check จากกฎจริงของ BKH Insight
// (src/app/api/fdh/c-check/checks.ts + files.ts) ไฟล์ที่สร้างห้ามแก้มือ: แก้กฎที่ checks.ts แล้วรันใหม่
//   node .claude/skills/fdh-c-check/scripts/export_rules.mjs          เขียนไฟล์
//   node .claude/skills/fdh-c-check/scripts/export_rules.mjs --check  ตรวจว่าไฟล์ตรงกับกฎปัจจุบัน (exit 1 ถ้าไม่ตรง)
// ต้องรันใน repo BKH Insight ด้วย node >= 23.6 (อ่าน .ts ได้เอง) ; โรงพยาบาลอื่นใช้ไฟล์ที่สร้างแล้วได้เลย ไม่ต้องรันสคริปต์นี้
import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const SKILL = fileURLToPath(new URL("..", import.meta.url));
const SRC = new URL("../../../../src/app/api/fdh/c-check/", import.meta.url);
const { CASE_LIMIT, RULES, casesSql, countDef, itemFiles, ruleSummarySql } = await import(new URL("checks.ts", SRC));
const { C_LEVEL, FILE_ORDER, FDH_TYPES, RULE_CODE_COUNT, STP_RULES, codeLevel, compareCode } = await import(new URL("files.ts", SRC));

// ชื่อ param ตามลำดับ `?` (mysql2/MariaDB) ; จำนวน ? ของแต่ละ statement คือ 2, 4 หรือ 6 เสมอ
const PARAMS = ["start", "end", "sel_json", "closed_json", "lab_csv", "cat_csv"];
// รหัสที่ c_codes.json ของ fdh-pre-validate ยังไม่มี: ข้อความจากตารางรหัส C ของ e-Claim (rep_error_code ของ BKH Insight)
const EXTRA_CODES = {
  "952": {
    code: "C952",
    detail: "รายการ item เบิกแต่ละหมวด หรือยอดเงินเกินจำนวนที่กำหนด",
    detail_source: "eclaim_code_table",
    fix: "ตรวจสอบ 1. รายการ item ที่เบิกในแต่ละหมวดต้องไม่เกิน 999 รายการ หรือ 2. ราคาหัตถการในหน้า F3 ต้องไม่เกิน 99,999 บาท หรือ 3. รหัส CLINIC ต้องไม่เกิน 5 หลัก แก้ไขให้ถูกต้องและกดบันทึกใหม่อีกครั้ง",
  },
};

const qCount = (sql) => sql.split("?").length - 1;
const header = (title, sql, extra = []) => {
  const n = qCount(sql);
  assert.ok([2, 4, 6].includes(n), `${title}: ? = ${n}`);
  return [
    `-- fdh-c-check: ${title}`,
    "-- GENERATED by scripts/export_rules.mjs from BKH Insight src/app/api/fdh/c-check/checks.ts - do not edit by hand",
    `-- params (${n}, in order of the placeholders): ${PARAMS.slice(0, n).join(", ")}`,
    ...extra.map((l) => `-- ${l}`),
    "",
  ].join("\n");
};

/** ชื่อตารางที่ SQL อ่าน (ไม่นับ CTE) */
const tablesOf = (sql) => {
  const cte = new Set([...sql.matchAll(/(?:WITH|,)\s*\n?\s*([a-z_][a-z0-9_]*) AS \(/gi)].map((m) => m[1].toLowerCase()));
  return [...sql.matchAll(/\b(?:FROM|JOIN)\s+([a-z_][a-z0-9_]*)/gi)].map((m) => m[1].toLowerCase()).filter((t) => !cte.has(t) && t !== "json_table");
};

/** path ใน skill -> เนื้อหา */
export function render() {
  const out = new Map();
  const tables = new Set();
  const manifest = {
    note: "GENERATED by scripts/export_rules.mjs - see SKILL.md",
    params: {
      start: "YYYY-MM-DD วันเริ่ม (op = vstdate, ip = dchdate)",
      end: "YYYY-MM-DD วันสิ้นสุด (รวมวันนี้)",
      sel_json: "JSON array ของ VN (op) / AN (ip) แบบตัวเลข เช่น [690915083012] ; '[]' = ทั้งช่วง (มีผลเฉพาะ cases_*)",
      closed_json: "JSON array ของ VN ที่ปิดสิทธิผ่านระบบอื่นที่ไม่ย้อนเข้า HOSxP (กฎ C305/C349) ; '[]' = ไม่มี",
      lab_csv: "icode ของแล็บหมวด 07 ที่ได้ TMLT คั่นด้วย , (กฎ C914) ; '' = แล็บหมวด 07 ทุกรายการติด C914",
      cat_csv: "lab_code ใน Lab Catalog FDH ของหน่วยบริการ คั่นด้วย , (กฎ C190) ; '' = แล็บหมวด 07 ทุกรายการติด C190",
    },
    case_limit: CASE_LIMIT,
    types: {},
  };
  const put = (path, title, sql, extra) => {
    assert.ok(/^[\x09\x0a\x0d\x20-\x7e]*$/.test(sql), `${path}: SQL ต้องเป็น ASCII (ฐาน HOSxP หลายแห่งเป็น tis620)`);
    tablesOf(sql).forEach((t) => tables.add(t));
    out.set(path, `${header(title, sql, extra)}${sql};\n`);
    return { sql: path, params: PARAMS.slice(0, qCount(sql)) };
  };

  for (const t of FDH_TYPES) {
    const items = itemFiles(t);
    const type = { date: t === "op" ? "vstdate" : "dchdate", files: {}, summary: [] };
    type.summary.push(put(`sql/${t}/summary.sql`, `${t} summary of every rule file that does not read opitemrece (${Object.keys(RULES[t]).filter((f) => !items.includes(f)).join(", ")})`, ruleSummarySql(t), ["returns c_code, fdh_file, n"]));
    for (const f of items) type.summary.push(put(`sql/${t}/summary_${f}.sql`, `${t} summary of ${f} (reads opitemrece: run alone, one statement at a time)`, ruleSummarySql(t, f), ["returns c_code, fdh_file, n"]));
    for (const f of FILE_ORDER[t]) {
      const { sql, col } = countDef(t, f);
      const rule = RULES[t][f];
      type.files[f] = {
        rows: { ...put(`sql/${t}/rows_${f}.sql`, `${t} row count of ${f}`, sql, [`returns ${col}`]), col },
        codes: rule?.codes ?? [],
        reads_opitemrece: !!rule?.items,
        ...(rule && {
          cases: put(`sql/${t}/cases_${f}.sql`, `${t} cases of ${f}: codes ${rule.codes.join(" ")}`, casesSql(t, f), [
            `returns c_code, hn, an, seq, found ; at most ${CASE_LIMIT} rows (edit the LIMIT at the end; ask LIMIT ${CASE_LIMIT + 1} to know it was cut)`,
            "found of C104/C116 is the citizen id: mask it before showing (1234xxxxx5678)",
          ]),
        }),
      };
    }
    manifest.types[t] = type;
  }

  // ทุกตารางที่กฎอ่าน: preflight คืนชื่อที่ฐานนี้ไม่มี (ว่าง = ครบ)
  const names = [...tables].sort();
  manifest.tables = names;
  const preflight = `SELECT x.name AS missing_table FROM (${names.map((n, i) => `SELECT '${n}'${i ? "" : " AS name"}`).join(" UNION ALL ")}) x
LEFT JOIN information_schema.tables it ON it.table_schema = DATABASE() AND it.table_name = x.name
WHERE it.table_name IS NULL`;
  out.set("sql/preflight.sql", `-- fdh-c-check: tables every rule reads that this database does not have (empty result = all present)\n-- GENERATED by scripts/export_rules.mjs - do not edit by hand\n-- params: none\n\n${preflight};\n`);
  out.set("sql/manifest.json", `${JSON.stringify(manifest, null, 2)}\n`);

  // ระดับ: ทุกรหัสที่มีกฎ (C ของ สปสช. + STP-*)
  const all = new Set();
  for (const t of FDH_TYPES) for (const r of Object.values(RULES[t])) r.codes.forEach((c) => all.add(c));
  const codes = [...all].sort(compareCode);
  assert.equal(codes.filter((c) => !c.startsWith("STP-")).length, RULE_CODE_COUNT);
  assert.ok(Object.keys(C_LEVEL).every((c) => all.has(c)), "C_LEVEL มีรหัสที่ไม่มีกฎ");
  const levels = {
    note: "GENERATED by scripts/export_rules.mjs. error = ติด C แน่ ; warn = อาจถูกตีกลับ ; info = ยังไม่ยืนยันว่ากองทุนตรวจ (ไม่นับเป็นติด C) ; ปรับตาม backtest กับ REP (ดู SKILL.md)",
    levels: Object.fromEntries(codes.map((c) => [c, codeLevel(c)])),
  };
  out.set("references/levels.json", `${JSON.stringify(levels, null, 2)}\n`);

  // c_codes.json = ของ fdh-pre-validate + 952 + STP-* + level ของรหัสที่มีกฎ
  const base = JSON.parse(readFileSync(join(SKILL, "../fdh-pre-validate/references/c_codes.json"), "utf8"));
  const merged = { ...base.codes, ...EXTRA_CODES };
  for (const [code, r] of Object.entries(STP_RULES)) merged[code] = { code, detail: r.detail, detail_source: "bkh_insight_stp_rules", fix: r.fix };
  for (const c of codes) {
    assert.ok(merged[c], `ไม่มีคำอธิบายของ ${c}`);
    merged[c] = { ...merged[c], level: codeLevel(c) };
  }
  const cCodes = {
    meta: {
      ...base.meta,
      notes: [
        ...base.meta.notes,
        "fdh-c-check: คัดจาก fdh-pre-validate แล้วเพิ่ม C952, กฎกองทุน STP (STP-*, ไม่ใช่รหัสของ สปสช.) และ level ของรหัสที่มีกฎตรวจ (ไม่มี level = ไม่มีกฎ)",
      ],
    },
    codes: Object.fromEntries(Object.keys(merged).sort(compareCode).map((k) => [k, merged[k]])),
  };
  out.set("references/c_codes.json", `${JSON.stringify(cCodes, null, 2)}\n`);
  return out;
}

// รันตรง (ไม่ใช่ถูก import จาก test) ; Windows ตัวพิมพ์ของไดรฟ์ต่างกันได้
if (process.argv[1] && resolve(process.argv[1]).toLowerCase() === fileURLToPath(import.meta.url).toLowerCase()) {
  const check = process.argv.includes("--check");
  const drift = [];
  for (const [path, body] of render()) {
    const file = join(SKILL, path);
    let cur = null;
    try { cur = readFileSync(file, "utf8"); } catch {}
    if (cur === body) continue;
    if (check) drift.push(path);
    else {
      mkdirSync(dirname(file), { recursive: true });
      writeFileSync(file, body);
      console.log("wrote", path);
    }
  }
  if (drift.length) {
    console.error(`fdh-c-check ไม่ตรงกับกฎปัจจุบัน (รัน export_rules.mjs ใหม่):\n${drift.join("\n")}`);
    process.exit(1);
  }
}
